#!/usr/bin/env node
// Creates musickit-config.js containing an Apple Music developer token (valid ~6 months).
//
// Usage:
//   node tools/make-musickit-token.mjs --team TEAMID --key KEYID --p8 ~/keys/AuthKey_KEYID.p8 \
//        [--origin https://my-mac.tailnet.ts.net] [--days 180]
//
// Keep the .p8 file OUTSIDE this folder: everything in this folder gets served to the iPads.
import { createPrivateKey, sign } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
const { team, key, p8 } = args;
if (!team || !key || !p8) {
  console.error('Usage: node tools/make-musickit-token.mjs --team TEAMID --key KEYID --p8 /path/to/AuthKey.p8 [--origin https://host] [--days 180]');
  process.exit(1);
}
const days = Math.min(Number(args.days || 180), 182); // Apple's limit is 6 months
const now = Math.floor(Date.now() / 1000);
const payload = { iss: team, iat: now, exp: now + days * 86400 };
if (args.origin) payload.origin = args.origin.split(',').map((s) => s.trim()).concat('http://localhost:8642');

const b64 = (obj) => Buffer.from(JSON.stringify(obj)).toString('base64url');
const input = b64({ alg: 'ES256', kid: key }) + '.' + b64(payload);
const pem = readFileSync(resolve(p8.replace(/^~(?=\/)/, homedir())), 'utf8');
const sig = sign('sha256', Buffer.from(input), { key: createPrivateKey(pem), dsaEncoding: 'ieee-p1363' });
const token = input + '.' + sig.toString('base64url');

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'musickit-config.js');
writeFileSync(out, `// Generated by tools/make-musickit-token.mjs. Expires ${new Date(payload.exp * 1000).toDateString()}.\nwindow.MUSICKIT_TOKEN = '${token}';\n`);
console.log('Wrote', out, '- expires', new Date(payload.exp * 1000).toDateString());
